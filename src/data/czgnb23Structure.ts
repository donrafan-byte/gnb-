export function getCompaniasForDestacamento<
  T extends Pick<ZoneUnit, 'destacamento' | 'compania' | 'nivel'>,
>(units: T[], destacamento: DestacamentoId): string[] {
  const set = new Set<string>();
  for (const u of units) {
    if (u.destacamento === destacamento && u.compania && u.nivel !== 'destacamento') {
      set.add(u.compania);
    }
  }
  if (set.size === 0) {
    for (const u of INITIAL_ZONE_UNITS) {
      if (u.destacamento === destacamento && u.compania && u.nivel !== 'destacamento') {
        set.add(u.compania);
      }
    }
  }
  return Array.from(set);
}

export function getPuestosForCompania<
  T extends Pick<ZoneUnit, 'destacamento' | 'compania' | 'nivel'>,
>(units: T[], destacamento: DestacamentoId, compania?: string): T[] {
  return units.filter(
    (u) =>
      u.destacamento === destacamento &&
      u.nivel === 'puesto_pac' &&
      (!compania || u.compania === compania)
  );
}
